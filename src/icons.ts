export type IconName = keyof typeof registry;

export function icon(name: IconName, size = 18, extraClass = "") {
  // Mỗi icon của lucide là ["svg", thuộc tính, [các phần tử con]]
  const [, , children] = registry[name] as unknown as [string, unknown, [string, Record<string, string | number>][]];
  const body = children
    .map(([tag, attrs]) => {
      const attributes = Object.entries(attrs ?? {})
        .map(([key, value]) => `${key}="${value}"`)
        .join(" ");
      return `<${tag} ${attributes}/>`;
    })
    .join("");

  return `<svg class="ic ${extraClass}" xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.9" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${body}</svg>`;
}
